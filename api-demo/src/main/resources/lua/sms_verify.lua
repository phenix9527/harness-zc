-- ============================================================================
-- 短信验证码校验（原子）
--
-- 为什么必须原子：如果先 GET 判断、再 DEL，两个并发请求拿着同一个验证码会同时通过
-- （「校验成功立即失效防重放」这条规则就失效了）。所以判断 + 删除必须在一次 Lua 里完成。
-- 顺带在这里做「错误次数限制」：6 位数字仅 100 万种可能，不限制次数等于把验证码白送。
--
-- KEYS[1] = 验证码 key，例如 sms:code:LOGIN:13800000000
-- KEYS[2] = 错误计数 key，例如 sms:fail:LOGIN:13800000000
-- ARGV[1] = 用户输入的验证码
-- ARGV[2] = 错误计数窗口秒数（例如 3600）
-- ARGV[3] = 最大允许错误次数（例如 5）
--
-- 返回值：
--    1  校验成功（已删除验证码与错误计数，防重放）
--    0  验证码不存在或已过期
--   -1  验证码错误（已累加错误次数）
--   -2  验证码错误且错误次数超限（验证码已被作废，需要重新发送）
--
-- 注意点：
--   1. 校验成功就 DEL，用户如果「填错两次再填对」也能通过（错误计数会一起清）。
--   2. 错误次数超限后作废验证码，防止有人用同一验证码暴力穷举。
--   3. 别在这里做「自动重新发送」：短信按条计费，被刷就是真花钱。
-- ============================================================================

local code = redis.call('GET', KEYS[1])
if not code then
    return 0
end

if code == ARGV[1] then
    redis.call('DEL', KEYS[1])
    redis.call('DEL', KEYS[2])
    return 1
end

local fails = redis.call('INCR', KEYS[2])
if fails == 1 then
    redis.call('EXPIRE', KEYS[2], ARGV[2])
end
if fails >= tonumber(ARGV[3]) then
    redis.call('DEL', KEYS[1])
    return -2
end
return -1
